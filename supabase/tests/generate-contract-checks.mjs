// Generates supabase/tests/database/004_contracts_match.test.sql from packages/contracts so the seeded
// role permissions and entitlement definitions can never drift from the TypeScript catalogue.
// Usage: node supabase/tests/generate-contract-checks.mjs  (Node ≥ 22.18 strips TS types natively)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const load = (p) => import(pathToFileURL(join(root, p)).href);
const { DEFAULT_ROLE_PERMISSIONS } = await load('packages/contracts/src/permissions.ts');
const { ENTITLEMENTS } = await load('packages/contracts/src/features.ts');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rolePairs = Object.entries(DEFAULT_ROLE_PERMISSIONS)
  .flatMap(([role, perms]) => perms.map((p) => `(${q(role)}, ${q(p)})`))
  .sort();
const entitlementRows = Object.entries(ENTITLEMENTS)
  .map(([key, def]) => `(${q(key)}, ${q(def.type)}, ${q(JSON.stringify(def.safeDefault))}::jsonb)`)
  .sort();

const sql = `-- GENERATED by supabase/tests/generate-contract-checks.mjs from packages/contracts. Do not edit by hand.
begin;
create extension if not exists pgtap with schema extensions;
select plan(2);

select results_eq(
  $$ select role, permission from public.role_permissions order by role, permission $$,
  $$ select role, permission from (values
       ${rolePairs.join(',\n       ')}
     ) as v(role, permission) order by role, permission $$,
  'role_permissions matches DEFAULT_ROLE_PERMISSIONS in @ds/contracts'
);

select results_eq(
  $$ select key, value_type, default_value from public.entitlement_definitions order by key $$,
  $$ select key, value_type, default_value from (values
       ${entitlementRows.join(',\n       ')}
     ) as v(key, value_type, default_value) order by key $$,
  'entitlement_definitions matches ENTITLEMENTS in @ds/contracts'
);

select * from finish();
rollback;
`;

writeFileSync(join(root, 'supabase/tests/database/004_contracts_match.test.sql'), sql);
console.log(`wrote role pairs: ${rolePairs.length}, entitlements: ${entitlementRows.length}`);
