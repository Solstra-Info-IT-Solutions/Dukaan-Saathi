// Generates supabase/tests/database/002_money_fixtures.test.sql from
// packages/domain-core/fixtures/money-cases.json so SQL and TypeScript run the same cases.
// Usage: node supabase/tests/generate-money-fixtures.mjs  (CI fails if the output is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const cases = JSON.parse(readFileSync(join(root, 'packages/domain-core/fixtures/money-cases.json'), 'utf8'));

const lines = [];
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

for (const c of cases.lineGross) {
  lines.push(
    `select is(private.line_gross(${c.unitPricePaise}, ${c.quantityMilli}), ${c.expected}::bigint, ${q(`line_gross(${c.unitPricePaise}, ${c.quantityMilli})`)});`,
  );
}
for (const c of cases.taxFromInclusive) {
  lines.push(
    `select is(private.tax_from_inclusive(${c.amountPaise}, ${c.rateBp}), ${c.expected}::bigint, ${q(`tax_from_inclusive(${c.amountPaise}, ${c.rateBp})`)});`,
  );
}
for (const c of cases.allocate) {
  lines.push(
    `select is(private.allocate_proportionally(${c.total}, array[${c.weights.join(',')}]::bigint[]), array[${c.expected.join(',')}]::bigint[], ${q(`allocate(${c.total}, [${c.weights}])`)});`,
  );
}
for (const c of cases.bills) {
  const billLines = c.lines.map((l) => ({
    unitPricePaise: l.unitPricePaise,
    quantityMilli: l.quantityMilli,
    ...(l.lineDiscountPaise ? { lineDiscountPaise: l.lineDiscountPaise } : {}),
    ...(l.taxRateBp ? { taxRateBp: l.taxRateBp } : {}),
  }));
  const call = `private.compute_bill(${q(JSON.stringify(billLines))}::jsonb, ${c.billDiscountPaise}, ${q(c.taxMode)}, ${c.roundOffEnabled})`;
  lines.push(
    `select is(${call} - 'lines', ${q(JSON.stringify(c.expected))}::jsonb, ${q(`compute_bill: ${c.name}`)});`,
  );
}
for (const c of cases.financialYear) {
  lines.push(
    `select is(private.financial_year(${q(c.instant)}::timestamptz), ${q(c.expected)}, ${q(`financial_year(${c.instant})`)});`,
  );
}

const sql = `-- GENERATED by supabase/tests/generate-money-fixtures.mjs from packages/domain-core/fixtures/money-cases.json.
-- Do not edit by hand. Bill-level fixtures are added when private.compute_bill exists (Phase 04).
begin;
create extension if not exists pgtap with schema extensions;
select plan(${lines.length});

${lines.join('\n')}

select * from finish();
rollback;
`;

writeFileSync(join(root, 'supabase/tests/database/002_money_fixtures.test.sql'), sql);
console.log(`wrote ${lines.length} assertions`);
